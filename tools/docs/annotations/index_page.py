"""Write the documentation notes page from the notes database.

The page lists every open note, grouped by the page it belongs to, so a reading
pass turns into a worklist. It is generated, so it is regenerated by the
documentation tasks and ignored by Git.
"""

from __future__ import annotations

import json
import sys
import urllib.error
import urllib.request
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from service import HOST, PORT  # noqa: E402

# DuckDB holds an exclusive lock for the life of a connection, so the running
# service is the only reader of the file. Ask it over HTTP instead.
NOTES_URL = f"http://{HOST}:{PORT}/notes"

OUTPUT = Path(__file__).resolve().parents[3] / "docs" / "todo" / "README.md"

HEADER = """# Documentation notes

Notes added while reading. Hover a block on any page to add one; this page is
regenerated by the documentation tasks.

"""

EMPTY = """No open notes, or the notes service is not running.

Inside Aspire the service starts with the stack. Serving the documentation any
other way, start it with `mise run docs:notes`, then select some text on any
page to comment on it.
"""


def open_notes() -> list[dict] | None:
    """Open notes from the running service, or None when it is not running."""
    try:
        with urllib.request.urlopen(NOTES_URL, timeout=3) as response:
            return json.load(response).get("notes", [])
    except (urllib.error.URLError, TimeoutError, json.JSONDecodeError, OSError):
        return None


def render() -> str:
    notes = open_notes()
    if not notes:
        return HEADER + EMPTY

    grouped: dict[tuple[str, str], list[dict]] = defaultdict(list)
    for note in notes:
        grouped[(note["page_title"] or note["page_path"], note["page_path"])].append(note)

    counts = defaultdict(int)
    for note in notes:
        counts[note["kind"]] += 1
    summary = ", ".join(f"{counts[kind]} {kind}" for kind in sorted(counts))

    pages = "page" if len(grouped) == 1 else "pages"
    lines = [HEADER.rstrip(), "", f"{len(notes)} open ({summary}) across {len(grouped)} {pages}.", ""]

    for (title, path), page_notes in sorted(grouped.items()):
        lines.append(f"## [{title}]({path})")
        lines.append("")
        lines.append("| Kind | Note | Block |")
        lines.append("| --- | --- | --- |")
        for note in page_notes:
            preview = (note["block_preview"] or "").replace("|", "\\|")[:90]
            body = note["body"].replace("\n", " ").replace("|", "\\|")
            heading = note["heading"].replace("|", "\\|")
            where = f"{heading} — {preview}…" if heading else f"{preview}…"
            lines.append(f"| {note['kind']} | {body} | {where} |")
        lines.append("")

    return "\n".join(lines) + "\n"


def main() -> int:
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(render(), encoding="utf-8")
    print(f"documentation notes page: {OUTPUT.relative_to(OUTPUT.parents[2])}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
